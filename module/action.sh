#!/system/bin/sh
# ============================================================
#  定时启动 App —— Magisk 模块动作按钮
#  在 Magisk / KernelSU 管理器里点击模块的「执行」按钮时运行，
#  立即执行一次完整流程（强制停止 → 解锁 → 启动）。
# ============================================================

MODDIR=${0%/*}

echo "立即执行一次定时任务..."
sh "$MODDIR/run_app.sh"
RC=$?

echo "执行结束，返回码 $RC"
echo "日志：/data/local/tmp/apptimer.log"
exit "$RC"
